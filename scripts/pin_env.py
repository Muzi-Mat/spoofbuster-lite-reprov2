"""Rewrite environment.yml with the package versions installed in THIS environment.

Run it in the environment that produced the results (the Colab runtime) and commit the output, so
environment.yml pins the versions actually used rather than versions someone guessed."""
import platform
from importlib.metadata import PackageNotFoundError, version


def installed(name):
    try:
        return version(name)
    except PackageNotFoundError:
        return None


PKGS = ["keras", "numpy", "pandas", "scikit-learn", "scikit-image", "matplotlib"]
OPENCV = ["opencv-python-headless", "opencv-python", "opencv-contrib-python"]

tf = next((p for p in ("tensorflow", "tensorflow-cpu") if installed(p)), None)
if tf is None:
    raise SystemExit("tensorflow is not installed here")
pins = [f"{tf}=={installed(tf)}"] + [f"{p}=={installed(p)}" for p in PKGS if installed(p)]
cv = next((p for p in OPENCV if installed(p)), None)
if cv:
    pins.append(f"opencv-python-headless=={installed(cv)}")  # headless: no GUI needed
missing = [p for p in PKGS if not installed(p)]
if missing:
    raise SystemExit(f"not installed here: {missing}")

py = ".".join(platform.python_version_tuple()[:2])
lines = ["# Generated by scripts/pin_env.py in the environment that produced results/ (see README).",
         "name: spoofbuster-lite-repro", "channels:", "  - conda-forge", "dependencies:",
         f"  - python={py}", "  - pip", "  - pip:"] + [f"      - {p}" for p in pins]
with open("environment.yml", "w") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines))
